#!/bin/bash
# Build the wasm Wine runtime (Hangover-style): Wine's unix side + wineserver + vnhost.
#
# env: EMSDK4 (emsdk with emscripten >= 4.0), WINE_SRC (patched Wine source),
#      WINE_TOOLS (native Wine build tree for winebuild/makedep), BUILD (build dir), OUT
set -e
EMSDK4=${EMSDK4:-/home/user/emsdk4}
WINE_SRC=${WINE_SRC:-/home/user/work/wine-src}
WINE_TOOLS=${WINE_TOOLS:-/home/user/img/buildroot/tmp/vnbox-build/wine-build-src/build}
BUILD=${BUILD:-/home/user/work/wine-wb4}
OUT=${OUT:-/home/user/work/hangover-out}
# FreeType built with emscripten (static, -fPIC; see the README)
FREETYPE=${FREETYPE:-/home/user/work/freetype-wasm}
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(dirname "$HERE")
. "$EMSDK4/emsdk_env.sh" >/dev/null 2>&1

mkdir -p "$BUILD" "$OUT"
cd "$BUILD"
if [ ! -f Makefile ] || [ "$WINE_SRC/configure" -nt Makefile ] || [ "$HERE/build.sh" -nt Makefile ]; then
  emconfigure "$WINE_SRC/configure" --host=i386-pc-linux-gnu --build=x86_64-pc-linux-gnu \
    --with-wine-tools="$WINE_TOOLS" --prefix=/opt/wine-vnbox --disable-tests --without-mingw \
    --without-x --without-wayland --without-vulkan --without-opengl \
    --without-pulse --without-alsa --without-oss --without-gstreamer --without-ffmpeg \
    --without-cups --without-dbus --without-gnutls --without-krb5 --without-netapi --without-sdl \
    --without-udev --without-usb --without-v4l2 --without-capi --without-pcap --without-pcsclite \
    --without-sane --without-gphoto --without-inotify --without-fontconfig --without-xinput2 \
    CFLAGS="-O2 -D__i386__ -pthread -fPIC -sSUPPORT_LONGJMP=wasm" \
    FREETYPE_CFLAGS="-I$FREETYPE/include/freetype2" FREETYPE_LIBS="-L$FREETYPE/lib -lfreetype" \
    ac_cv_lib_soname_freetype=libfreetype.so.6 > configure.log 2>&1
fi
make -j"$(nproc)" dlls/ntdll/ntdll.so > make.log 2>&1
# the server objects; linking wineserver on its own fails (it lives in our module) and that's fine
make -j"$(nproc)" -k server/wineserver >> make.log 2>&1 || true

cd "$ROOT"
RUSTC_BOOTSTRAP=1 RUSTFLAGS="-C target-feature=+atomics,+bulk-memory,+mutable-globals -C relocation-model=pic -C panic=abort" \
  cargo build --release -p vnhost --target wasm32-unknown-emscripten -Zbuild-std=std,panic_abort
VNHOST=$ROOT/target/wasm32-unknown-emscripten/release/libvnhost.a

WRAP="socket socketpair pipe pipe2 bind listen accept accept4 connect shutdown setsockopt getsockopt
  getsockname getpeername sendmsg recvmsg send recv sendto recvfrom read write readv writev close dup dup2
  poll select fstat lseek fcntl ioctl mmap munmap mprotect madvise msync mlock mremap dlopen dlsym dlclose
  dlerror dladdr kill pthread_kill isatty getpid exit _exit getenv setenv unsetenv putenv pthread_create
  open openat creat stat lstat fstatat access faccessat readlink mkdir rmdir unlink rename symlink link
  chmod utimensat chdir fchdir getcwd realpath opendir fdopendir readdir closedir rewinddir dirfd pread
  pwrite ftruncate fsync fchmod futimens fstatfs fstatvfs posix_fallocate fgetxattr fsetxattr
  fremovexattr getxattr fopen fdopen"
WRAPFLAGS=$(for w in $WRAP; do printf -- "-Wl,--wrap=%s " "$w"; done)

# Wine's unix libraries other than ntdll. They all go into one module, so the symbols each one
# exports by name are renamed (<lib>__wine_unix_call_funcs, ...) and registered under the
# library's file name for dlopen()/dlsym() (crates/vnhost/src/dl.rs).
# dlls/<dir>/<name>.so; <dir> defaults to <name>
UNIXLIBS="ws2_32 win32u winebrowser.drv/winebrowser dnsapi nsiproxy.sys/nsiproxy mountmgr.sys/mountmgr winebus.sys/winebus crypt32 secur32 msv1_0 netapi32 localspl winspool.drv/winspool"
UNIXSYMS="__wine_unix_call_funcs __wine_unix_call_wow64_funcs __wine_unix_lib_init"
LIB_OBJS=
REG="$OUT/unixlibs.c"
printf '/* generated by hangover/build.sh */\nstruct sym { const char *name; const void *addr; };\n' > "$REG"
printf 'extern void vnhost_register_unixlib( const char *name, const struct sym *syms );\n' >> "$REG"
REG_CALLS=
cd "$BUILD"
NM="$EMSDK/upstream/bin/llvm-nm"
# global symbols already taken (by ntdll or an earlier library): a library defining one of them
# gets it renamed to <lib>_<symbol>
TAKEN=$("$NM" --defined-only -g -j dlls/ntdll/unix/*.o | sort -u)
for ent in $UNIXLIBS; do
  case $ent in */*) dir=${ent%/*}; lib=${ent#*/} ;; *) dir=$ent; lib=$ent ;; esac
  objs=$(awk -v t="dlls/$dir/$lib.so:" '$1==t{on=1} on{for(i=1;i<=NF;i++) if($i ~ /\.o$/) print $i; if($NF!="\\") exit}' Makefile)
  marker="dlls/$dir/.vnvm-renamed"
  cflags=$(sed -n 's/^CFLAGS = //p' Makefile)
  for pass in 1 2; do
    defs=$(for s in $UNIXSYMS; do printf -- "-D%s=%s%s " "$s" "$lib" "$s"; done)
    [ $pass = 2 ] && defs="$(cat "$marker") $(comm -12 <(echo "$TAKEN") <("$NM" --defined-only -g -j $objs | grep -v "^$lib" | sort -u) |
      while read -r s; do if [ -n "$s" ]; then printf -- "-D%s=%s_%s " "$s" "$lib" "$s"; fi; done)"
    [ $pass = 2 ] && defs=$(echo $defs | tr ' ' '\n' | awk '!seen[$0]++' | tr '\n' ' ')
    [ $pass = 1 ] && [ -f "$marker" ] && defs=$(cat "$marker")
    [ "$(cat "$marker" 2>/dev/null)" = "$defs" ] || rm -f $objs
    make -j"$(nproc)" CFLAGS="$cflags $defs" $objs >> make.log 2>&1
    echo "$defs" > "$marker"
  done
  TAKEN=$( (echo "$TAKEN"; "$NM" --defined-only -g -j $objs) | sort -u)
  LIB_OBJS="$LIB_OBJS $(for o in $objs; do printf '%s/%s ' "$BUILD" "$o"; done)"
  defined=$("$NM" --defined-only -j $objs)
  entries=
  for s in $UNIXSYMS; do
    if echo "$defined" | grep -qx "$lib$s"; then
      if [ $s = __wine_unix_lib_init ]; then printf 'extern void %s%s(void);\n' "$lib" "$s" >> "$REG"
      else printf 'extern char %s%s[];\n' "$lib" "$s" >> "$REG"; fi
      entries="$entries{ \"$s\", $lib$s }, "
    fi
  done
  printf 'static const struct sym %s_syms[] = { %s{ 0 } };\n' "$lib" "$entries" >> "$REG"
  REG_CALLS="$REG_CALLS    vnhost_register_unixlib( \"$lib.so\", ${lib}_syms );\n"
done
# FreeType: win32u dlopen()s it and looks up what freetype.c loads with LOAD_FUNCPTR
FT_SYMS=$(sed -n 's/^ *LOAD_FUNCPTR(\(FT_[A-Za-z_]*\)).*/\1/p' "$WINE_SRC/dlls/win32u/freetype.c" | sort -u)
for s in $FT_SYMS; do printf 'extern void %s(void);\n' "$s" >> "$REG"; done
printf 'static const struct sym freetype_syms[] = { %s{ 0 } };\n' "$(for s in $FT_SYMS; do printf '{ "%s", %s }, ' "$s" "$s"; done)" >> "$REG"
REG_CALLS="$REG_CALLS    vnhost_register_unixlib( \"libfreetype.so.6\", freetype_syms );\n"
printf 'static void __attribute__((constructor)) register_unixlibs( void )\n{\n%b}\n' "$REG_CALLS" >> "$REG"
cd "$ROOT"
emcc -O2 -pthread -fPIC -c "$REG" -o "$OUT/unixlibs.o"

# Wine's unix side: one instance per Wine process (see crates/vnhost/src/proc.rs)
# (wasm-ld's --wrap crashes on side modules, so its imports are renamed afterwards)
emcc -O2 -pthread -sSUPPORT_LONGJMP=wasm -sSIDE_MODULE=1 $SIDE_EXTRA -Wl,--export=__wine_main -o "$OUT/wineunix.so" "$BUILD"/dlls/ntdll/unix/*.o \
  $LIB_OBJS "$OUT/unixlibs.o" "$FREETYPE/lib/libfreetype.a" \
  2> "$OUT/side.log" || { cat "$OUT/side.log"; exit 1; }
python3 "$HERE/wrap-imports.py" "$OUT/wineunix.so" $WRAP

# the main module: wineserver, vnhost and libc; keep vnhost's C API for the side module
KEEP=$("$EMSDK/upstream/bin/llvm-nm" --defined-only -j "$VNHOST" 2>/dev/null | grep -E '^(vnhost_|__wrap_)' | sort -u | sed 's/^/-Wl,-u,/')
emcc -O2 -pthread -fPIC -c "$HERE/main.c" -o "$OUT/main.o"
emcc -O2 -pthread -fPIC -c "$ROOT/crates/vnhost/c/shim.c" -o "$OUT/shim.o"
link_main() {  # <output .js> <emcc flags...>
  local out=$1
  shift
  emcc -O2 -pthread -fwasm-exceptions -sSUPPORT_LONGJMP=wasm -sMAIN_MODULE=1 -o "$out" "$OUT/main.o" "$OUT/shim.o" \
    $(cd "$BUILD" && ls server/*.o | sed "s|^|$BUILD/|") "$VNHOST" $KEEP \
    $WRAPFLAGS --pre-js "$HERE/pre.js" --js-library "$HERE/vnfs.js" --js-library "$HERE/vnjit.js" \
    -sPROXY_TO_PTHREAD -sEXIT_RUNTIME \
    -sGLOBAL_BASE=2147483648 -sINITIAL_MEMORY=2214592512 -sMAXIMUM_MEMORY=4GB -sALLOW_MEMORY_GROWTH=1 \
    -sSTACK_SIZE=1MB -sDEFAULT_PTHREAD_STACK_SIZE=1MB -sPTHREAD_POOL_SIZE=16 -sPTHREAD_POOL_SIZE_STRICT=0 \
    -sERROR_ON_UNDEFINED_SYMBOLS=1 -sDEFAULT_LIBRARY_FUNCS_TO_INCLUDE=__assert_fail "$@" $EXTRA_LDFLAGS \
    2> "$OUT/link.log" || { grep -i "undefined\|error" "$OUT/link.log" | sort -u | head -80; exit 1; }
}
# node: the host's files through NODERAWFS
link_main "$OUT/wine.js" -sNODERAWFS=1 -sENVIRONMENT=node
# the page (web/wine.html): an ES module factory; files come from the store (vfs) and MEMFS
WEB_OUT=${WEB_OUT:-$ROOT/web/public/wine}
mkdir -p "$WEB_OUT"
link_main "$WEB_OUT/wine.js" -sENVIRONMENT=web,worker -sMODULARIZE -sEXPORT_ES6 -sEXPORT_NAME=createWine \
  -sFORCE_FILESYSTEM -sEXPORTED_RUNTIME_METHODS=FS,ENV,HEAPU8,HEAPU32,HEAPF32 \
  -sEXPORTED_FUNCTIONS=_main,_malloc,_vnhost_display_size,_vnhost_display_frame,_vnhost_input_push,_vnhost_audio_take
cp "$OUT/wineunix.so" "$WEB_OUT/"
echo "built $OUT/wine.js and $WEB_OUT/wine.js"
