#!/bin/bash
# Regenerate image/wine-runtime-packages.txt from a build-wine.sh BUILDROOT:
# the packages owning every library vnbox's Wine links (ldd) or dlopens
# (SONAME_* in its config.h). New WoW64 has no i386 unix side, so this is all
# amd64.
set -euo pipefail
B=$(realpath "${1:?BUILDROOT}")
HERE=$(cd "$(dirname "$0")" && pwd)
sonames=$( {
  grep '#define SONAME_' "$B"/tmp/vnbox-build/wine-build-src/build/include/config.h | awk '{print $3}' | tr -d '"'
  for f in "$B"/opt/wine-vnbox/lib/wine/x86_64-unix/*.so "$B"/opt/wine-vnbox/bin/wine*; do
    chroot "$B" ldd "${f#"$B"}" 2>/dev/null | awk '/=>/ {print $1}'
  done
} | sort -u)
{
  echo "# Runtime libraries of vnbox's Wine on Ubuntu 26.04: packages owning every soname"
  echo "# its unix side links or dlopens (generated by image/wine-runtime-deps.sh)."
  for s in $sonames; do chroot "$B" dpkg -S "*/$s" 2>/dev/null | head -1 | cut -d: -f1; done |
    sort -u | grep -v '^libwine$'
  # Mesa (llvmpipe) for wined3d's GL renderer; the IPA fonts for the msfonts step.
  echo libgl1-mesa-dri; echo fonts-ipafont-gothic; echo fonts-ipafont-mincho
} > "$HERE/wine-runtime-packages.txt"
